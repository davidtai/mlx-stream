#!/usr/bin/env python3
"""Write the generated texts of src/kernels/glm5_next_exl3_forms/: DeepSeek-V4.1's served decode forms (src/kernels/exl3
b3 texts) at GLM-5.3-Flash's expert shape, by exact text replacement (each count is checked), for the kernel bench and
the forms routes (src/arch/glm5_next/exl3_forms.zig). The arithmetic, its order and the bank reads stay the DeepSeek
texts'. Run from the repository root; `--check` compares, writes nothing.

  g5k3_guone    dsv41_exl3_b3_guone_k3_2304 (gate and up in one launch; unroll 8 kept)        IT, OT
  g5k3_pair     dsv41_exl3_b3_pair_k3_5120  (the down form: a slot's rows paired, one decode)  IT, OT
  g5k3_gemv_u8  dsv41_exl3_b3_mul1h_k3_2304 (the gate / up GEMV as DeepSeek runs it, unroll 8) IT, OT
  g5k3_gemv_mcg glm5n_exl3_gemv with the mul1 decode replaced by exllamav3's mcg decode (codebook.cuh L67-75:
                x *= 0xCBAC1FED; x = (x & 0x8FFF8FFF) ^ 0x3B603B60; the f16 sum of its two halves), the bench's
                codebook price only (no mcg bank is served)
The fused forms (g5k3_gu_fused, g5k3_dn_fused, header_g5k3) are written by hand.
"""
import os
import sys

SRC = 'src/kernels/exl3'
GLM = 'src/kernels/glm5_next_exl3'
DST = 'src/kernels/glm5_next_exl3_forms'


def sub(text, pairs, name):
    for old, new, count in pairs:
        n = text.count(old)
        if n != count:
            sys.exit(f'{name}: "{old}" occurs {n} times, expected {count}')
        text = text.replace(old, new)
    return text


def head(name, base, what):
    return (f'// {name} (mlx-stream glm5_next exl3 forms, generated by scripts/glm5next_exl3_forms_gen.py): {base}.metal\n'
            f'// with its shape literals as template constants ({what}); the arithmetic is the base text\'s.\n')


def read(d, base):
    with open(os.path.join(d, base + '.metal')) as f:
        return f.read()


OUT = {}
# DEVROUTE `hit_wave: resident_only` (glm5next_exl3_kernels_gen.py): a pair whose id is 0xFFFFFFFF returns first.
IDS_ONE = 'uint sid = ids[row]; uint bk = sid >> 24u;'
SKIP_ONE = (IDS_ONE, IDS_ONE + '\n        if (sid == 0xFFFFFFFFu) return; // a missed pair of the device hit wave (hit_wave: resident_only)', 1)
IDS_PAIR = 'uint slot = ids[row];\n'
SKIP_PAIR = (IDS_PAIR, IDS_PAIR + '        if (slot == 0xFFFFFFFFu) return; // a missed pair of the device hit wave (hit_wave: resident_only)\n', 1)
OUT['g5k3_guone'] = head('g5k3_guone', 'exl3/dsv41_exl3_b3_guone_k3_2304', 'IT, OT') + sub(read(SRC, 'dsv41_exl3_b3_guone_k3_2304'), [
    ('* 2211840ul', '* (ulong(IT) * ulong(OT) * 48ul)', 1),
    ('row * 5120u', 'row * (uint(IT) * 16u)', 1),
    ('tk < 320u', 'tk < uint(IT)', 1),
    ('(tk * 144u + tn)', '(tk * uint(OT) + tn)', 1),
    ('[row * 2304u', '[row * (uint(OT) * 16u)', 1),
    SKIP_ONE,
], 'guone')
OUT['g5k3_pair'] = head('g5k3_pair', 'exl3/dsv41_exl3_b3_pair_k3_5120', 'IT, OT') + sub(read(SRC, 'dsv41_exl3_b3_pair_k3_5120'), [
    ('* 2211840ul', '* (ulong(IT) * ulong(OT) * 48ul)', 1),
    ('row * 2304u', 'row * (uint(IT) * 16u)', 1),
    ('mate * 2304u', 'mate * (uint(IT) * 16u)', 1),
    ('tk < 144u', 'tk < uint(IT)', 2),
    ('(tk * 320u + tn)', '(tk * uint(OT) + tn)', 2),
    ('[row * 5120u', '[row * (uint(OT) * 16u)', 2),
    ('[mate * 5120u', '[mate * (uint(OT) * 16u)', 1),
    SKIP_PAIR,
], 'pair')
OUT['g5k3_gemv_u8'] = head('g5k3_gemv_u8', 'exl3/dsv41_exl3_b3_mul1h_k3_2304', 'IT, OT') + sub(read(SRC, 'dsv41_exl3_b3_mul1h_k3_2304'), [
    ('* 2211840ul', '* (ulong(IT) * ulong(OT) * 48ul)', 1),
    ('xh + row * 5120u', 'xh + row * (uint(IT) * 16u)', 1),
    ('tk < 320u', 'tk < uint(IT)', 1),
    ('(tk * 144u + tn)', '(tk * uint(OT) + tn)', 1),
    ('out[row * 2304u', 'out[row * (uint(OT) * 16u)', 1),
], 'gemv_u8')
MUL1 = ('                uint rr = window * 0x83DCD12Du;\n'
        '                uint bs = (rr & 0x00FF00FFu) + ((rr >> 8u) & 0x00FF00FFu);\n'
        '                half hs = as_type<half>(ushort((bs * 0x00010001u + 0x64000000u) >> 16u));\n'
        '                float w = float(fma(hs, as_type<half>(ushort(0x1EEEu)), as_type<half>(ushort(0xC931u))));\n')
MCG = ('                uint rr = ((window * 0xCBAC1FEDu) & 0x8FFF8FFFu) ^ 0x3B603B60u;\n'
       '                half2 hh = as_type<half2>(rr);\n'
       '                float w = float(hh.x + hh.y);\n')
glm_gemv = read(GLM, 'glm5n_exl3_gemv')
glm_gemv = glm_gemv[glm_gemv.index('\n', glm_gemv.index('\n') + 1) + 1:]  # drop the generator's two-line head
OUT['g5k3_gemv_mcg'] = ('// g5k3_gemv_mcg (mlx-stream glm5_next exl3 forms, generated by scripts/glm5next_exl3_forms_gen.py): glm5n_exl3_gemv\n'
                        '// with the mul1 decode replaced by exllamav3\'s mcg decode (the bench\'s codebook price; no mcg bank is served).\n'
                        + sub(glm_gemv, [(MUL1, MCG, 2)], 'gemv_mcg'))

check = '--check' in sys.argv
bad = 0
for name, text in OUT.items():
    path = os.path.join(DST, name + '.metal')
    if check:
        have = open(path).read() if os.path.exists(path) else None
        if have != text:
            print(f'STALE {path}')
            bad += 1
        continue
    with open(path, 'w') as f:
        f.write(text)
print('glm5next exl3 forms gen: ' + ('%d stale' % bad if check else 'wrote %d texts' % len(OUT)))
sys.exit(1 if bad else 0)
