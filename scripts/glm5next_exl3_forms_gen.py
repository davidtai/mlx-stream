#!/usr/bin/env python3
"""Write the generated texts of src/kernels/glm5_next_exl3_forms/: DeepSeek-V4.1's served decode forms (src/kernels/exl3
b3 texts) at GLM-5.3-Flash's expert shape, by exact text replacement (each count is checked), for the kernel bench and
the forms routes (src/arch/glm5_next/exl3_forms.zig). The arithmetic, its order and the bank reads stay the DeepSeek
texts'. Run from the repository root; `--check` compares, writes nothing.

  g5k3_guone    dsv41_exl3_b3_guone_k3_2304 (gate and up in one launch; unroll 8 kept)        IT, OT
  g5k3_pair     dsv41_exl3_b3_pair_k3_5120  (the down form: a slot's rows paired, one decode)  IT, OT
"""
import os
import sys

SRC = 'src/kernels/exl3'
DST = 'src/kernels/glm5_next_exl3_forms'


def sub(text, pairs, name):
    for old, new, count in pairs:
        n = text.count(old)
        if n != count:
            sys.exit(f'{name}: "{old}" occurs {n} times, expected {count}')
        text = text.replace(old, new)
    return text


def head(name, base, what):
    return (f'// {name} (mlx-stream glm5_next exl3 forms, generated by scripts/glm5next_exl3_forms_gen.py): {base}.metal\n'
            f'// with its shape literals as template constants ({what}); the arithmetic is the base text\'s.\n')


def read(d, base):
    with open(os.path.join(d, base + '.metal')) as f:
        return f.read()


OUT = {}
OUT['g5k3_guone'] = head('g5k3_guone', 'exl3/dsv41_exl3_b3_guone_k3_2304', 'IT, OT') + sub(read(SRC, 'dsv41_exl3_b3_guone_k3_2304'), [
    ('* 2211840ul', '* (ulong(IT) * ulong(OT) * 48ul)', 1),
    ('row * 5120u', 'row * (uint(IT) * 16u)', 1),
    ('tk < 320u', 'tk < uint(IT)', 1),
    ('(tk * 144u + tn)', '(tk * uint(OT) + tn)', 1),
    ('[row * 2304u', '[row * (uint(OT) * 16u)', 1),
], 'guone')
OUT['g5k3_pair'] = head('g5k3_pair', 'exl3/dsv41_exl3_b3_pair_k3_5120', 'IT, OT') + sub(read(SRC, 'dsv41_exl3_b3_pair_k3_5120'), [
    ('* 2211840ul', '* (ulong(IT) * ulong(OT) * 48ul)', 1),
    ('row * 2304u', 'row * (uint(IT) * 16u)', 1),
    ('mate * 2304u', 'mate * (uint(IT) * 16u)', 1),
    ('tk < 144u', 'tk < uint(IT)', 2),
    ('(tk * 320u + tn)', '(tk * uint(OT) + tn)', 2),
    ('[row * 5120u', '[row * (uint(OT) * 16u)', 2),
    ('[mate * 5120u', '[mate * (uint(OT) * 16u)', 1),
], 'pair')

check = '--check' in sys.argv
bad = 0
for name, text in OUT.items():
    path = os.path.join(DST, name + '.metal')
    if check:
        have = open(path).read() if os.path.exists(path) else None
        if have != text:
            print(f'STALE {path}')
            bad += 1
        continue
    with open(path, 'w') as f:
        f.write(text)
print('glm5next exl3 forms gen: ' + ('%d stale' % bad if check else 'wrote %d texts' % len(OUT)))
sys.exit(1 if bad else 0)
