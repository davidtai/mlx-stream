#!/usr/bin/env python3
"""Write src/kernels/glm5_next_exl3/*.metal: the DeepSeek-V4.1 EXL3 K=3 mul1h texts (src/kernels/exl3/) with their
shape literals replaced by template constants, so one text serves GLM-5.3-Flash's expert shape (hidden 4096, inter
2048) as a compile-time instantiation. Every replacement is exact text (each count is checked); the arithmetic, its
order and the bank reads stay the DeepSeek text's. Run from the repository root; `--check` compares, writes nothing.

Template constants (the Zig seam `src/arch/glm5_next/exl3_kernels.zig` binds them):
  HID    the expert input width of gate / up and the output width of down (4096)
  INTER  the expert intermediate width (2048)
  IT, OT the GEMV's input / output tile counts (width / 16)
  KD, ND the DIG-X GEMM's reduction / output widths
  SGS    the onepass epilogue's simdgroups per threadgroup (DeepSeek: 6 for 18 blocks; GLM: 8 for 16 blocks)
"""
import hashlib
import os
import sys

SRC = 'src/kernels/exl3'
DST = 'src/kernels/glm5_next_exl3'


def sub(text, pairs, name):
    for old, new, count in pairs:
        n = text.count(old)
        if n != count:
            sys.exit(f'{name}: "{old}" occurs {n} times, expected {count}')
        text = text.replace(old, new)
    return text


def head(name, base, what):
    return (f'// {name} (mlx-stream glm5_next exl3, generated by scripts/glm5next_exl3_kernels_gen.py): {base}.metal of\n'
            f'// src/kernels/exl3 with its shape literals as template constants ({what}); the arithmetic is the base text\'s.\n')


def read(base):
    with open(os.path.join(SRC, base + '.metal')) as f:
        return f.read()


OUT = {}

# ── Decode: the banked PREP=rin chain (ids packed bank << 24 | slot row over the base, ext and transient banks) ──

OUT['glm5n_exl3_in_rin'] = head('glm5n_exl3_in_rin', 'dsv41_exl3_b3_prep_in_rin', 'HID') + sub(
    read('dsv41_exl3_b3_prep_in_rin'), [('row * 5120u', 'row * uint(HID)', 4)], 'in_rin')

# The GEMV of one projection: code [rows, IT, OT, 48] i16, xh f32 [P, IT * 16] -> z f32 [P, OT * 16].
OUT['glm5n_exl3_gemv'] = head('glm5n_exl3_gemv', 'dsv41_exl3_b3_mul1h_k3_2304', 'IT, OT') + sub(
    read('dsv41_exl3_b3_mul1h_k3_2304'), [
        ('* 2211840ul', '* (ulong(IT) * ulong(OT) * 48ul)', 1),
        ('xh + row * 5120u', 'xh + row * (uint(IT) * 16u)', 1),
        ('#pragma clang loop unroll_count(8)', '#pragma clang loop unroll_count(4)', 1),
        ('tk < 320u', 'tk < uint(IT)', 1),
        ('(tk * 144u + tn)', '(tk * uint(OT) + tn)', 1),
        ('out[row * 2304u', 'out[row * (uint(OT) * 16u)', 1),
    ], 'gemv')

OUT['glm5n_exl3_gu_epi'] = head('glm5n_exl3_gu_epi', 'dsv41_exl3_b3_prep_gu_epi', 'INTER') + sub(
    read('dsv41_exl3_b3_prep_gu_epi'), [('out[row * 2304u', 'out[row * uint(INTER)', 2)], 'gu_epi')

OUT['glm5n_exl3_din_rin'] = head('glm5n_exl3_din_rin', 'dsv41_exl3_b3_prep_din_rin', 'INTER') + sub(
    read('dsv41_exl3_b3_prep_din_rin'), [('out[row * 2304u', 'out[row * uint(INTER)', 2)], 'din_rin')

# dpost stores its f32 word in the template dtype T (bf16: the expert output type the glm5_next combines read; one
# rounding on store, the DIG-X rot_widen1_obf16 idiom).
OUT['glm5n_exl3_dpost'] = head('glm5n_exl3_dpost', 'dsv41_exl3_b3_moeprep_dpost', 'HID, T') + sub(
    read('dsv41_exl3_b3_moeprep_dpost'), [
        ('out[row * 5120u + c0] = (B[tid] * SCALE) * float(BANKED_rd(c0));', 'out[row * uint(HID) + c0] = static_cast<T>((B[tid] * SCALE) * float(BANKED_rd(c0)));', 1),
        ('out[row * 5120u + c1] = (B[tid + 64u] * SCALE) * float(BANKED_rd(c1));', 'out[row * uint(HID) + c1] = static_cast<T>((B[tid + 64u] * SCALE) * float(BANKED_rd(c1)));', 1)], 'dpost')

# ── Prompt: DIG-X (the trellis decoded in the NAX GEMMs' B loader), DIG2 onepass ──

OUT['glm5n_exl3_take2v'] = head('glm5n_exl3_take2v', 'dsv41_prefill_dig_take2v_5120', 'HID') + sub(
    read('dsv41_prefill_dig_take2v_5120'), [('(int64_t) r * 5120', '(int64_t) r * HID', 1)], 'take2v')

OUT['glm5n_exl3_gemm_gu'] = head('glm5n_exl3_gemm_gu', 'dsv41_prefill_dig_gemm_5120x2304_gu_xmul1hk3_m128', 'KD, ND') + sub(
    read('dsv41_prefill_dig_gemm_5120x2304_gu_xmul1hk3_m128'), [
        ('constexpr int KD = 5120;\n', '', 1), ('constexpr int ND = 2304;\n', '', 1)], 'gemm_gu')

OUT['glm5n_exl3_gemm_dn'] = head('glm5n_exl3_gemm_dn', 'dsv41_prefill_dig_gemm_2304x5120_xmul1hk3_m128', 'KD, ND') + sub(
    read('dsv41_prefill_dig_gemm_2304x5120_xmul1hk3_m128'), [
        ('constexpr int KD = 2304;\n', '', 1), ('constexpr int ND = 5120;\n', '', 1)], 'gemm_dn')

OUT['glm5n_exl3_onepass'] = head('glm5n_exl3_onepass', 'q3_prefill_dig2_swiglu_2304_x', 'INTER, SGS') + sub(
    read('q3_prefill_dig2_swiglu_2304_x'), [
        ('threadgroup_position_in_grid.x * 6u', 'threadgroup_position_in_grid.x * uint(SGS)', 1),
        ('dig2_swiglu_one(', 'glm5n_dig2_swiglu_one(', 1),
        ('r, cb, l);', 'r, cb, l, uint(INTER));', 1)], 'onepass')

OUT['glm5n_exl3_widen1'] = head('glm5n_exl3_widen1', 'dsv41_prefill_dig_rot_widen1_5120_obf16', 'HID, T') + sub(
    read('dsv41_prefill_dig_rot_widen1_5120_obf16'), [
        ('(int64_t) r * 5120', '(int64_t) r * HID', 1),
        ('static_cast<bfloat16_t>(', 'static_cast<T>(', 1)], 'widen1')

# The onepass helper at a template width: header_dig2_x.metal's dig2_swiglu_one with its 2304 a parameter.
dig2 = read('header_dig2_x')
start = dig2.index('// one (row, 128-column block), one simdgroup')
end = dig2.index('// epilogue: the threadgroup')
one = sub(dig2[start:end], [
    ('METAL_FUNC void dig2_swiglu_one(', 'METAL_FUNC void glm5n_dig2_swiglu_one(', 1),
    ('const int slot, const int row, const int cb, const uint l) {', 'const int slot, const int row, const int cb, const uint l,\n                                      const uint inter) {', 1),
    ('size_t(2304)', 'size_t(inter)', 2)], 'dig2 header')
OUT['header_glm5n_exl3_dig2'] = ('// header_glm5n_exl3_dig2 (generated by scripts/glm5next_exl3_kernels_gen.py): header_dig2_x.metal\'s\n'
                                 '// dig2_swiglu_one with its width a parameter, appended to header_dig2_x.metal at bind.\n' + one)

check = '--check' in sys.argv
bad = 0
for name, text in OUT.items():
    path = os.path.join(DST, name + '.metal')
    if check:
        have = open(path).read() if os.path.exists(path) else None
        if have != text:
            print(f'STALE {path}')
            bad += 1
        continue
    with open(path, 'w') as f:
        f.write(text)
    print(f'{name} {hashlib.sha256(text.encode()).hexdigest()}')
sys.exit(1 if bad else 0)
