//! DeepSeek conversation checkpoint manifest. Tensor payloads are separate, streamed files; this module never
//! constructs an MLX array. A validated manifest describes one reusable boundary, not an active HTTP generation.
const std = @import("std");

pub const version: u32 = 1;
pub const max_manifest_bytes: usize = 16 << 20;
pub const max_parse_bytes: usize = 32 << 20;
pub const Digest = [32]u8;
pub const TensorId = u32;
pub const Identity = struct {
    model: Digest,
    numerics: Digest,
    context: u32,
};
pub const Dtype = enum {
    bf16,
    f32,
    pub fn size(self: Dtype) u64 {
        return if (self == .bf16) 2 else 4;
    }
};
pub const Tensor = struct {
    dtype: Dtype,
    shape: []const u32,
    bytes: u64,
    sha256: Digest,
};
pub const Ring = struct {
    window: u32,
    cap_keep: u32,
    phys_cap: u32,
    base_phys_cap: u32,
    cur: u1,
    len: u32,
    drop: u32,
    caps: [2]u32,
    bufs: [2]?TensorId,
};
pub const Lane = struct { len: u32, tensor: ?TensorId };
pub const Layer = struct {
    offset: u32,
    window: Ring,
    compress: Lane,
    index: Lane,
    frontier: ?struct { kv: Ring, score: Ring } = null,
};
pub const Draft = struct { offset: u32, window: ?TensorId };
pub const Checkpoint = struct {
    format_version: u32,
    identity: Identity,
    /// Exact token prefix represented by this boundary, including any generated tokens only if explicitly captured.
    prompt_ids: []const u32,
    hash_history: []const i64,
    layers: []const Layer,
    draft: []const Draft,
    main: ?TensorId,
    tensors: []const Tensor,
};

/// Model-derived limits, never supplied by the checkpoint. The caller pins identity to model content and all
/// numerical/runtime settings, not a path, mtime or model display name. Ring and store geometry must match too.
pub const Limits = struct {
    identity: Identity,
    vocab: u32,
    layers: []const LayerGeometry,
    head_dim: u32,
    index_dim: u32,
    hidden: u32,
    main_taps: u32,
    draft_stages: u32,
    window: u32,
    max_positions: u32,
    max_ring_capacity: u32,
    ring_keep: u32,
    ring_headroom: u32,
    hash_enabled: bool,
    max_tensor_bytes: u64,
    max_total_bytes: u64,
};
pub const LayerGeometry = struct { ratio: u32, kv_source: bool };
pub const Error = error{ SnapshotVersion, SnapshotIdentity, SnapshotLimit, SnapshotGeometry, SnapshotTensor, SnapshotChecksum };

pub fn digest(bytes: []const u8) Digest {
    var out: Digest = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &out, .{});
    return out;
}

/// Check metadata and references before reading payloads or allocating GPU state. Canonical ordinal payload names
/// are generated by the caller; this manifest contains no filesystem paths. Each tensor must have exactly one owner.
pub fn validate(cp: Checkpoint, lim: Limits) Error!u64 {
    if (cp.format_version != version) return error.SnapshotVersion;
    if (!std.meta.eql(cp.identity, lim.identity)) return error.SnapshotIdentity;
    if (cp.prompt_ids.len == 0 or cp.prompt_ids.len > lim.max_positions)
        return error.SnapshotLimit;
    for (cp.prompt_ids) |id| if (id >= lim.vocab) return error.SnapshotGeometry;
    if (cp.hash_history.len != (if (lim.hash_enabled) cp.prompt_ids.len else @as(usize, 0))) return error.SnapshotGeometry;
    if (cp.layers.len != lim.layers.len or cp.layers.len > 256 or cp.draft.len != lim.draft_stages) return error.SnapshotGeometry;
    if (cp.tensors.len > 2048) return error.SnapshotLimit;
    var used: [2048]bool = @splat(false);
    var total: u64 = 0;
    for (cp.tensors) |t| {
        if (t.shape.len == 0 or t.shape.len > 8) return error.SnapshotTensor;
        var n = t.dtype.size();
        for (t.shape) |d| {
            if (d == 0) return error.SnapshotTensor;
            n = std.math.mul(u64, n, d) catch return error.SnapshotLimit;
        }
        if (n != t.bytes) return error.SnapshotTensor;
        if (n > lim.max_tensor_bytes) return error.SnapshotLimit;
        total = std.math.add(u64, total, n) catch return error.SnapshotLimit;
        if (total > lim.max_total_bytes) return error.SnapshotLimit;
    }
    const offset: u32 = @intCast(cp.prompt_ids.len);
    for (cp.layers, lim.layers) |layer, geo| {
        if (layer.offset != offset) return error.SnapshotGeometry;
        try checkRing(cp, &used, layer.window, lim, lim.window, offset, .bf16, lim.head_dim);
        if (geo.kv_source and geo.ratio == 0) return error.SnapshotGeometry;
        const rows = if (geo.kv_source) offset / geo.ratio else 0;
        try checkLane(cp, &used, layer.compress, rows, .bf16, lim.head_dim);
        try checkLane(cp, &used, layer.index, rows, .f32, lim.index_dim);
        if (geo.kv_source and geo.ratio > 1) {
            const frontier = layer.frontier orelse return error.SnapshotGeometry;
            try checkRing(cp, &used, frontier.kv, lim, geo.ratio, offset, .f32, lim.head_dim);
            try checkRing(cp, &used, frontier.score, lim, geo.ratio, offset, .f32, lim.head_dim);
        } else if (layer.frontier != null) return error.SnapshotGeometry;
    }
    for (cp.draft) |d| {
        if (d.offset != offset) return error.SnapshotGeometry;
        const id = d.window orelse return error.SnapshotTensor;
        if (id >= cp.tensors.len) return error.SnapshotTensor;
        const shape = cp.tensors[id].shape;
        if (shape.len != 3 or shape[1] == 0 or shape[1] > @min(offset, lim.window)) return error.SnapshotTensor;
        // The head preserves the tap dtype; appending to an existing f32 window also preserves f32.
        // Both enum dtypes are valid here, with the recorded bytes restored without a conversion.
        try checkTensor(cp, &used, d.window, cp.tensors[id].dtype, &.{ 1, shape[1], lim.head_dim });
    }
    if (cp.main) |id| {
        if (lim.draft_stages == 0) return error.SnapshotGeometry;
        // A completed boundary trimmed to the visible output has no valid last-main row; the required nonempty
        // continuation recreates it before drafting, just as the in-memory boundary path does.
        if (id >= cp.tensors.len) return error.SnapshotTensor;
        // mainOf preserves the stream's bf16 or f32 dtype, which may differ between prompt and decode.
        try checkTensor(cp, &used, cp.main, cp.tensors[id].dtype, &.{ 1, 1, lim.main_taps * lim.hidden });
    }
    for (used[0..cp.tensors.len]) |u| if (!u) return error.SnapshotTensor;
    return total;
}

fn checkTensor(cp: Checkpoint, used: *[2048]bool, id: ?TensorId, dtype: Dtype, shape: []const u32) Error!void {
    const i = id orelse {
        std.log.warn("DeepSeek checkpoint: missing tensor, expected {t} {any}", .{ dtype, shape });
        return error.SnapshotTensor;
    };
    if (i >= cp.tensors.len or used[i]) {
        std.log.warn("DeepSeek checkpoint: tensor reference {d} invalid or reused ({d} tensors)", .{ i, cp.tensors.len });
        return error.SnapshotTensor;
    }
    const t = cp.tensors[i];
    if (t.dtype != dtype or !std.mem.eql(u32, t.shape, shape)) {
        std.log.warn("DeepSeek checkpoint tensor {d}: {t} {any}, expected {t} {any}", .{ i, t.dtype, t.shape, dtype, shape });
        return error.SnapshotTensor;
    }
    used[i] = true;
}
fn checkLane(cp: Checkpoint, used: *[2048]bool, lane: Lane, rows: u32, dtype: Dtype, width: u32) Error!void {
    if (lane.len != rows) return error.SnapshotGeometry;
    if (rows == 0) {
        if (lane.tensor != null) return error.SnapshotTensor;
    } else try checkTensor(cp, used, lane.tensor, dtype, &.{ 1, rows, width });
}
fn checkRing(cp: Checkpoint, used: *[2048]bool, ring: Ring, lim: Limits, window: u32, offset: u32, dtype: Dtype, width: u32) Error!void {
    const keep = std.math.add(u32, window, lim.ring_keep) catch return error.SnapshotLimit;
    const base = std.math.add(u32, keep, lim.ring_headroom) catch return error.SnapshotLimit;
    if (ring.window != window or ring.cap_keep != keep or ring.base_phys_cap != base or ring.phys_cap < base or
        ring.phys_cap > lim.max_ring_capacity or ring.len > ring.phys_cap or ring.len == 0 or
        (ring.drop > 0 and @as(u64, ring.len) + 1 < window) or
        @as(u64, ring.drop) + ring.len != offset) return error.SnapshotGeometry;
    for (ring.bufs, ring.caps, 0..) |buf, cap, i| {
        if (i == ring.cur) {
            if (cap != ring.phys_cap) return error.SnapshotGeometry;
            try checkTensor(cp, used, buf, dtype, &.{ 1, cap, width });
        } else if (buf != null or cap != 0) return error.SnapshotGeometry;
    }
}

/// Only small metadata is allocated here. Tensor bytes are independently streamed and hashed by the caller.
pub fn encode(a: std.mem.Allocator, cp: Checkpoint, lim: Limits) ![]u8 {
    _ = try validate(cp, lim);
    const out = try std.json.Stringify.valueAlloc(a, cp, .{});
    errdefer a.free(out);
    if (out.len > max_manifest_bytes) return error.SnapshotLimit;
    return out;
}
pub const Parsed = struct {
    value: Checkpoint,
    inner: std.json.Parsed(Checkpoint),
    allocator: std.mem.Allocator,
    bounded: *std.heap.FixedBufferAllocator,
    backing: []u8,
    pub fn deinit(self: *Parsed) void {
        self.inner.deinit();
        self.allocator.destroy(self.bounded);
        self.allocator.free(self.backing);
    }
};

pub fn decode(a: std.mem.Allocator, bytes: []const u8, expected_digest: Digest, lim: Limits) !Parsed {
    if (bytes.len > max_manifest_bytes) return error.SnapshotLimit;
    if (!std.mem.eql(u8, &digest(bytes), &expected_digest)) return error.SnapshotChecksum;
    const backing = try a.alloc(u8, max_parse_bytes);
    errdefer a.free(backing);
    const bounded = try a.create(std.heap.FixedBufferAllocator);
    errdefer a.destroy(bounded);
    bounded.* = .init(backing);
    var parsed = try std.json.parseFromSlice(Checkpoint, bounded.allocator(), bytes, .{ .allocate = .alloc_always, .ignore_unknown_fields = false });
    errdefer parsed.deinit();
    _ = try validate(parsed.value, lim);
    return .{ .value = parsed.value, .inner = parsed, .allocator = a, .bounded = bounded, .backing = backing };
}

/// Incremental payload verification uses constant memory; callers must finish this before constructing MLX arrays.
pub const PayloadHash = struct {
    hash: std.crypto.hash.sha2.Sha256 = .init(.{}),
    seen: u64 = 0,
    pub fn update(self: *PayloadHash, bytes: []const u8, expected_bytes: u64) Error!void {
        const n = std.math.add(u64, self.seen, bytes.len) catch return error.SnapshotLimit;
        if (n > expected_bytes) return error.SnapshotTensor;
        self.hash.update(bytes);
        self.seen = n;
    }
    pub fn finish(self: *PayloadHash, tensor: Tensor) Error!void {
        if (self.seen != tensor.bytes) return error.SnapshotTensor;
        var got: Digest = undefined;
        self.hash.final(&got);
        if (!std.mem.eql(u8, &got, &tensor.sha256)) return error.SnapshotChecksum;
    }
};

const testing = std.testing;
fn fixture() Checkpoint {
    return comptime blk: {
        @setEvalBranchQuota(100000);
        break :blk .{ .format_version = version, .identity = .{ .model = @splat(1), .numerics = @splat(2), .context = 8 }, .prompt_ids = &.{ 1, 2 }, .hash_history = &.{ 3, 4 }, .layers = &.{.{ .offset = 2, .window = .{ .window = 2, .cap_keep = 2, .phys_cap = 2, .base_phys_cap = 2, .cur = 0, .len = 2, .drop = 0, .caps = .{ 2, 0 }, .bufs = .{ 0, null } }, .compress = .{ .len = 0, .tensor = null }, .index = .{ .len = 0, .tensor = null } }}, .draft = &.{}, .main = null, .tensors = &.{.{ .dtype = .bf16, .shape = &.{ 1, 2, 4 }, .bytes = 16, .sha256 = digest(&(@as([16]u8, @splat(7)))) }} };
    };
}
fn fixtureLimits() Limits {
    return .{ .identity = fixture().identity, .vocab = 16, .layers = &.{.{ .ratio = 1, .kv_source = false }}, .head_dim = 4, .index_dim = 2, .hidden = 4, .main_taps = 1, .draft_stages = 0, .window = 2, .max_positions = 16, .max_ring_capacity = 8, .ring_keep = 0, .ring_headroom = 0, .hash_enabled = true, .max_tensor_bytes = 128, .max_total_bytes = 256 };
}
test "dsv41 snapshot: checked manifest roundtrip preserves full ring geometry and hash history" {
    const cp = fixture();
    const bytes = try encode(testing.allocator, cp, fixtureLimits());
    defer testing.allocator.free(bytes);
    var parsed = try decode(testing.allocator, bytes, digest(bytes), fixtureLimits());
    defer parsed.deinit();
    try testing.expectEqualDeep(cp, parsed.value);
    var hash: PayloadHash = .{};
    const payload: [16]u8 = @splat(7);
    try hash.update(payload[0..3], 16);
    try hash.update(payload[3..], 16);
    try hash.finish(cp.tensors[0]);
}
test "dsv41 snapshot: foreign models versions malformed geometry and payloads refuse before allocation" {
    var cp = fixture();
    cp.identity.model[0] ^= 1;
    try testing.expectError(error.SnapshotIdentity, validate(cp, fixtureLimits()));
    cp = fixture();
    cp.format_version += 1;
    try testing.expectError(error.SnapshotVersion, validate(cp, fixtureLimits()));
    cp = fixture();
    cp.hash_history = &.{};
    try testing.expectError(error.SnapshotGeometry, validate(cp, fixtureLimits()));
    cp = fixture();
    var layers = cp.layers[0..1].*;
    layers[0].window.drop = 1;
    cp.layers = &layers;
    try testing.expectError(error.SnapshotGeometry, validate(cp, fixtureLimits()));
    cp = fixture();
    var tensors = cp.tensors[0..1].*;
    tensors[0].shape = &.{ 1, 2, 8 };
    cp.tensors = &tensors;
    try testing.expectError(error.SnapshotTensor, validate(cp, fixtureLimits()));
    var hash: PayloadHash = .{};
    try hash.update(&(@as([16]u8, @splat(8))), 16);
    try testing.expectError(error.SnapshotChecksum, hash.finish(fixture().tensors[0]));
    hash = .{};
    try hash.update(&.{7}, 16);
    try testing.expectError(error.SnapshotTensor, hash.finish(fixture().tensors[0]));
    try testing.expectError(error.SnapshotTensor, hash.update(&(@as([16]u8, @splat(7))), 16));
    const bytes = try encode(testing.allocator, fixture(), fixtureLimits());
    defer testing.allocator.free(bytes);
    try testing.expectError(error.SnapshotChecksum, decode(testing.allocator, bytes, @splat(0), fixtureLimits()));
}

test "dsv41 snapshot: completed tokens may use generation headroom beyond the prompt context" {
    var cp = fixture();
    var lim = fixtureLimits();
    cp.identity.context = 1;
    lim.identity = cp.identity;
    try testing.expectEqual(@as(u64, 16), try validate(cp, lim));
    lim.max_positions = 1;
    try testing.expectError(error.SnapshotLimit, validate(cp, lim));
}
